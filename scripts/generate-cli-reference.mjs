#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { chmodSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export function parseHelpCommands(help) {
  const block = help.match(/^Commands:\s*\n([\s\S]*?)(?=^\S|$(?![\s\S]))/m)?.[1] ?? '';
  return [...new Set([...block.matchAll(/^  ([a-z][a-z0-9-]*)(?:\s{2,}.*)?$/gm)].map((m) => m[1]))].sort();
}

export function catalogPaths(catalog, parent = []) {
  return (catalog.commands ?? []).flatMap((command) => {
    const path = [...parent, command.name];
    return [path, ...catalogPaths(command, path)];
  });
}

export function walkHelp(readHelp, seeds = []) {
  const pending = [[], ...seeds];
  const seen = new Map();
  while (pending.length) {
    const path = pending.shift();
    const key = path.join(' ');
    if (seen.has(key)) continue;
    const help = readHelp(path).replace(/\r\n/g, '\n').trim();
    if (!help) throw new Error(`empty help for hypertask ${key}`);
    seen.set(key, { path, help });
    for (const command of parseHelpCommands(help)) pending.push([...path, command]);
    if (seen.size > 1000) throw new Error('help tree exceeded 1000 commands');
  }
  return [...seen.values()].sort((a, b) => a.path.join(' ').localeCompare(b.path.join(' '), 'en'));
}

export function renderCliReference(entries, version) {
  const sections = entries.map(({ path, help }) => {
    const fence = '`'.repeat(Math.max(3, ...[...help.matchAll(/`+/g)].map((m) => m[0].length + 1)));
    return `## \`hypertask${path.length ? ' ' + path.join(' ') : ''}\`\n\n${fence}text\n${help}\n${fence}`;
  });
  return `---\ntitle: CLI Commands\ndescription: Every command exposed by the released Hypertask CLI, generated from its help.\n---\n\n{/* Generated by scripts/generate-cli-reference.mjs. Do not edit by hand. */}\n\n**Source:** Hypertask CLI \`${version}\`.\n\n**${entries.length - 1} commands.** Run any command with \`--help\` for its current usage.\n\n${sections.join('\n\n')}\n`;
}

async function main() {
  let temp;
  try {
    let bin = process.env.HYPERTASK_CLI_BIN;
    if (!bin) {
      temp = mkdtempSync(join(tmpdir(), 'docs-cli-'));
      execFileSync('gh', ['release', 'download', '-R', 'hypertask-ai/cli', '-p', 'hypertask-linux-x86_64', '-D', temp], { timeout: 120_000, stdio: ['ignore', 'pipe', 'pipe'] });
      bin = join(temp, 'hypertask-linux-x86_64');
      chmodSync(bin, 0o700);
    }
    // Help must never inherit an agent token or the operator's saved login.
    const home = temp ?? mkdtempSync(join(tmpdir(), 'docs-cli-'));
    temp = home;
    const env = { PATH: process.env.PATH, HOME: home, XDG_CONFIG_HOME: home, NO_COLOR: '1' };
    const run = (args) => execFileSync(resolve(bin), args, { encoding: 'utf8', env, timeout: 15_000, maxBuffer: 8 * 1024 * 1024 });
    const version = run(['--version']).trim();
    // v0.2.17 root help lists no commands; its embedded catalog supplies the roots.
    const catalog = JSON.parse(run(['capabilities', '--json']));
    const paths = catalogPaths(catalog);
    if (!paths.length) throw new Error('CLI catalog lists no commands');
    const entries = walkHelp((path) => run([...path, '--help']), paths);
    const out = new URL('../src/content/docs/cli/commands.mdx', import.meta.url);
    writeFileSync(out, renderCliReference(entries, version));
    console.log(`wrote ${fileURLToPath(out)}: ${entries.length - 1} commands (${version})`);
  } finally {
    if (temp) rmSync(temp, { recursive: true, force: true });
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  main().catch(() => { console.error('<3>CLI reference generation failed; check release download and CLI help'); process.exitCode = 1; });
}
